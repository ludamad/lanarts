#!/usr/bin/env python3
"""Builds the bosses' sprites, animations and spell effects from tools/bosses/<boss>.py.

    python3 tools/bosses/build.py                         # write everything under runtime/
    python3 tools/bosses/build.py --only royal_jelly --sheet /tmp/jelly.png --no-write   # review one

A boss module sets:
    NAME      key for its files: spr_bosses.<NAME> (base sprite), spr_animations.<NAME>.<animation>
    SOURCE    the art it starts from, relative to runtime/ (DCSS tiles: spr_enemies/...)
    CANVAS    the square size it is drawn at; the art sits bottom centre with room to move
    SCALE     optional: 2 doubles SOURCE with Scale2x first (a boss towering over the party)
    SHADOW    (cx, cy, rx, ry): its baked drop shadow, in SOURCE pixels (see creatures.split_shadow)
    CREATURE  keyword arguments for creatures.Creature (magic, accent, flying, heavy, waist, ...)
and may define:
    base(frame) -> frame   the boss's own look, drawn over the padded SOURCE (canvas pixels)
    effects() -> {name: [frames]}   projectile and spell sprites: spr_bosses.<name>, animated
                            (0.1 frames a step) when there is more than one frame

Writes runtime/spr_bosses/, runtime/spr_animations/<NAME>/ and runtime/enemies/bosses/BossAnimations.lua.
Rebuild the game afterwards (compile_images.py registers the new images). Needs Pillow.
"""
import argparse
import importlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "sprites"))
RUNTIME = os.path.abspath(os.path.join(HERE, "..", "..", "runtime"))

import rig                    # noqa: E402
import creatures              # noqa: E402

# Every module here but this one is a boss
BOSSES = sorted(f[:-3] for f in os.listdir(HERE) if f.endswith(".py") and f != "build.py")
STEP_SECONDS = 0.016
ORDER = ["idle", "walk", "attack", "cast", "hurt", "death"]
LOOPING = {"idle", "walk"}


def steps(seconds):
    return max(1, round(seconds / STEP_SECONDS))


def build(name):
    """-> (base frame, {animation: frames}, {animation: seconds per frame}, {effect: frames})"""
    m = importlib.import_module(name)
    src = rig.load(os.path.join(RUNTIME, m.SOURCE), None)
    scale = getattr(m, "SCALE", 1)
    for _ in range(scale // 2):
        src = rig.scale2x(src)
    h, w = len(src), len(src[0])
    ox, oy = (m.CANVAS - w) // 2, m.CANVAS - h - 4
    if ox < 0 or oy < 0:
        sys.exit(f"{name}: CANVAS {m.CANVAS} is too small for {w}x{h} art (it needs {max(w, h + 4)} or more)")
    base = rig.paste(rig.blank(m.CANVAS), src, ox, oy)
    if hasattr(m, "base"):
        base = m.base(base)
    shadow = getattr(m, "SHADOW", None)
    if shadow:
        shadow = (shadow[0] * scale + ox, shadow[1] * scale + oy, shadow[2] * scale, shadow[3] * scale)
    creature = creatures.Creature(base, shadow=shadow, pixel=scale, **getattr(m, "CREATURE", {}))
    anims = creature.all()
    timing = creatures.timing(anims, heavy=getattr(m, "CREATURE", {}).get("heavy", False))
    effects = m.effects() if hasattr(m, "effects") else {}
    return m, base, anims, timing, effects


def write_runtime(results):
    sprite_dir = os.path.join(RUNTIME, "spr_bosses")
    os.makedirs(sprite_dir, exist_ok=True)
    lua = ["-- Generated by tools/bosses/build.py: animation clips for the bosses. Do not edit.", ""]
    for m, base, anims, timing, effects in results:
        size = f"{m.CANVAS}x{m.CANVAS}"
        rig.to_image(base).save(os.path.join(sprite_dir, f"{m.NAME}.png"))
        out_dir = os.path.join(RUNTIME, "spr_animations", m.NAME)
        os.makedirs(out_dir, exist_ok=True)
        for stale in os.listdir(out_dir):  # clips of an earlier canvas size would clash by name
            os.remove(os.path.join(out_dir, stale))
        lua.append("Data.animation_set_create {")
        lua.append(f'    sprite = "spr_bosses.{m.NAME}",')
        for name in ORDER:
            rig.save_strip(anims[name], os.path.join(out_dir, f"{name}.{size}.png"))
            frames = ", ".join(str(steps(t)) for t in timing[name])
            loop = "true" if name in LOOPING else "false"
            lua.append(f'    {name} = {{ sprite = "spr_animations.{m.NAME}.{name}", frames = {{{frames}}}, loop = {loop} }},')
        lua.append("}")
        lua.append("")
        for effect, frames in effects.items():
            fh, fw = len(frames[0]), len(frames[0][0])
            path = os.path.join(sprite_dir, f"{effect}.png" if len(frames) == 1 else f"{effect}.{fw}x{fh}.png")
            rig.save_strip(frames, path)
    with open(os.path.join(RUNTIME, "enemies", "bosses", "BossAnimations.lua"), "w") as f:
        f.write("\n".join(lua))


def write_sheet(results, path, scale=3):
    from PIL import Image
    floor = Image.open(os.path.join(RUNTIME, "spr_tile_floors", "grey_dirt.png")).convert("RGBA").crop((0, 0, 32, 32))
    rows = []
    for m, base, anims, timing, effects in results:
        rows += [(m.CANVAS, anims[a]) for a in ORDER]
        rows += [(max(len(fr[0]), len(fr[0][0])), fr) for fr in effects.values()]
    cell = max(size for size, _ in rows) * scale + 6
    cols = max(len(frames) for _, frames in rows)
    sheet = Image.new("RGBA", (cols * cell, len(rows) * cell), (44, 40, 52, 255))
    for j, (size, frames) in enumerate(rows):
        for i, fr in enumerate(frames):
            fh, fw = len(fr), len(fr[0])
            bg = Image.new("RGBA", (fw, fh))
            for y in range(0, fh, 32):
                for x in range(0, fw, 32):
                    bg.paste(floor, (x, y))
            bg.alpha_composite(rig.to_image(fr))
            sheet.paste(bg.resize((fw * scale, fh * scale), Image.NEAREST), (i * cell + 3, j * cell + 3))
    sheet.save(path)


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--sheet", help="also write a review sheet PNG")
    p.add_argument("--only", help="comma separated boss modules")
    p.add_argument("--no-write", action="store_true", help="don't touch runtime/")
    args = p.parse_args()
    names = args.only.split(",") if args.only else BOSSES
    results = [build(n) for n in names]
    if not args.no_write:
        if args.only:
            sys.exit("--only is for previews; pass --no-write with it")
        write_runtime(results)
    if args.sheet:
        write_sheet(results, args.sheet)


if __name__ == "__main__":
    main()
