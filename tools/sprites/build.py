#!/usr/bin/env python3
"""Builds the animated player sprites.

    python3 tools/sprites/build.py                  # write strips + runtime/classes/AnimationSets.lua
    python3 tools/sprites/build.py --sheet out.png  # also render a review sheet of every rig
    python3 tools/sprites/build.py --only fighter   # restrict to some rigs (comma separated)

Strips go to runtime/spr_animations/<rig>/<animation>.32x32.png, registered by compile_images.py as
spr_animations.<rig>.<animation>. AnimationSets.lua ties them to the class sprites they animate.
Needs Pillow.
"""
import argparse
import importlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
RUNTIME = os.path.abspath(os.path.join(HERE, "..", "..", "runtime"))

import rig                    # noqa: E402
import animations             # noqa: E402
from rigs import RIGS         # noqa: E402

STEP_SECONDS = 0.016          # one game step (settings time_per_step)
ORDER = ["idle", "walk", "attack", "cast", "hurt", "death"]
LOOPING = {"idle", "walk"}


def steps(seconds):
    return max(1, round(seconds / STEP_SECONDS))


def animate(rig_name):
    """-> ({animation: frames}, {animation: seconds per frame})"""
    module = importlib.import_module(f"rigs.{rig_name}")
    animator = animations.Animator(module, RUNTIME)
    return animator.all(), animator.timing()


def write_runtime(results):
    lua = ["-- Generated by tools/sprites/build.py: animation clips for class sprites. Do not edit.", ""]
    for sprite_name, rig_name in RIGS.items():
        anims, timing = results[rig_name]
        out_dir = os.path.join(RUNTIME, "spr_animations", rig_name)
        os.makedirs(out_dir, exist_ok=True)
        lua.append("Data.animation_set_create {")
        lua.append(f'    sprite = "{sprite_name}",')
        for name in ORDER:
            rig.save_strip(anims[name], os.path.join(out_dir, f"{name}.32x32.png"))
            assert len(timing[name]) == len(anims[name]), (rig_name, name)
            frames = ", ".join(str(steps(t)) for t in timing[name])
            loop = "true" if name in LOOPING else "false"
            lua.append(f'    {name} = {{ sprite = "spr_animations.{rig_name}.{name}", frames = {{{frames}}}, loop = {loop} }},')
        lua.append("}")
        lua.append("")
    with open(os.path.join(RUNTIME, "classes", "AnimationSets.lua"), "w") as f:
        f.write("\n".join(lua))


def write_sheet(results, path, scale=5):
    from PIL import Image
    floor = Image.open(os.path.join(RUNTIME, "spr_tile_floors", "grey_dirt.png")).convert("RGBA").crop((0, 0, 32, 32))
    rows = [(r, a) for r in results for a in ORDER]
    cols = max(len(results[r][0][a]) for r, a in rows)
    cell = 32 * scale + 4
    sheet = Image.new("RGBA", (cols * cell + 4, len(rows) * cell + 4), (44, 40, 52, 255))
    for j, (r, a) in enumerate(rows):
        for i, fr in enumerate(results[r][0][a]):
            t = floor.copy()
            t.alpha_composite(rig.to_image(fr))
            sheet.alpha_composite(t.resize((32 * scale, 32 * scale), Image.NEAREST), (4 + i * cell, 4 + j * cell))
    sheet.save(path)


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--sheet", help="also write a review sheet PNG")
    p.add_argument("--only", help="comma separated rig names")
    p.add_argument("--no-write", action="store_true", help="don't touch runtime/")
    args = p.parse_args()
    names = args.only.split(",") if args.only else list(dict.fromkeys(RIGS.values()))
    results = {n: animate(n) for n in names}
    if not args.no_write:
        if args.only:
            sys.exit("--only is for previews; pass --no-write with it")
        write_runtime(results)
    if args.sheet:
        write_sheet(results, args.sheet)


if __name__ == "__main__":
    main()
