function M.loadout_preset_names()
    local names = {}
    local seen = {}
    for _, name in ipairs(M.loadout_order) do
        if M.loadout_presets[name] then
            names[#names + 1] = name
            seen[name] = true
        end
    end
    local extras = {}
    for name, _ in pairs(M.loadout_presets) do
        if not seen[name] then
            extras[#extras + 1] = name
        end
    end
    table.sort(extras)
    for _, name in ipairs(extras) do
        names[#names + 1] = name
    end
    return names
end

function M.catalog()
    return {
        schema = 1,
        classes = M.classes,
        levels = M.levels,
        loadouts = M.loadout_presets,
        loadout_names = M.loadout_preset_names(),
        class_builds = M.class_builds,
        item_choices = M.item_choices,
        intensities = M.intensities,
        maps = M.maps,
        map_algorithms = M.map_algorithms,
        encounters = M.encounters,
        resources = M.resources,
    }
end

return M
